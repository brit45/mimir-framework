#!/usr/bin/env python3
"""Generate/check editor helpers against the actual Lua reference registry."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]

def manifest(binary):
    with tempfile.TemporaryDirectory(prefix='mimir-api-') as work:
        script = Path(work) / 'api.lua'
        target = Path(work) / 'api.json'
        script.write_text('''local function describe(v)
  if type(v) == "function" then return {native_function=true} end
  if type(v) ~= "table" then return nil end
  local result = {}
  for k, item in pairs(v) do result[k] = describe(item) end
  return result
end
write_json(arg[1], describe(Mimir))
''')
        env = dict(os.environ, MIMIR_DISABLE_ROCM='1', MIMIR_DISABLE_CUDA='1',
                   MIMIR_DISABLE_VULKAN='1', MIMIR_DISABLE_OPENCL='1', OMP_NUM_THREADS='1')
        result = subprocess.run([str(Path(binary).resolve()), '--lua', str(script), str(target)],
                                cwd=ROOT, env=env, capture_output=True, text=True)
        if result.returncode or not target.exists():
            raise SystemExit('Native manifest failed:\n' + result.stdout + result.stderr)
        return json.loads(target.read_text())

def ts_type(source):
    # Preserve primitive, optional and array annotations; complex Lua table/class
    # schemas remain open objects because the native API accepts extensible configs.
    parts=[]
    for token in source.split('|'):
        optional=token.endswith('?'); token=token.removesuffix('?')
        if token.endswith('[]'): value=f'({ts_type(token[:-2])})[]'
        elif token.startswith('table'): value='Record<string, any>'
        else: value={'integer':'number','int':'number','float':'number','number':'number',
                     'boolean':'boolean','bool':'boolean','string':'string','nil':'null',
                     'any':'any','TokenIds':'number[]','TokenId':'number','bytes':'number',
                     'ArchitectureName':'string','ModelType':'string','DType':'string',
                     'WeightInit':'string','TokenText':'string'}.get(token, 'any')
        parts.append(value)
        if optional: parts.append('null')
    return ' | '.join(dict.fromkeys(parts))

def generate(api):
    lua_path = ROOT / 'ide/lua/mimir-api.lua'
    lua = lua_path.read_text()
    # Dynamic layer closures are registered by the reference registry too.
    for module, functions in sorted(api.items()):
        for name in sorted(functions):
            qualified = f'Mimir.{module}.{name}'
            if not re.search(r'^function '+re.escape(qualified)+r'\(', lua, re.M):
                lua += f'\n---Native API: {qualified}.\n---@param ... any\n---@return any\nfunction {qualified}(...) end\n'
    signatures = {}
    annotations = {}
    previous = 0
    for match in re.finditer(r'^function (Mimir\.\w+\.\w+)\(([^)]*)\) end', lua, re.M):
        signatures[match[1]] = match[2]
        block=lua[previous:match.start()]
        params={name: (kind, name.endswith('?')) for name,kind in re.findall(r'---@param\s+(\S+)\s+(\S+)', block)}
        annotations[match[1]] = {name.rstrip('?'): (kind, optional) for name,(kind,optional) in params.items()}
        previous=match.end()
    ts = ['// Generated by scripts/tools/generate_ide_helpers.py. Do not execute.',
          'type MimirValue = any;',
          'interface MimirFunction { (...args: any[]): any; results(...args: any[]): any[]; }',
          'declare namespace Mimir {']
    rs = ['// Generated from the native Lua registry. Do not edit.',
          '// Each argument list preserves Lua positional/optional arguments; use Value::Null to skip one.']
    for module, functions in sorted(api.items()):
        ts += [f'  namespace {module} {{']
        rs += [f'#[allow(non_snake_case)] pub mod {module} {{']
        for name in sorted(functions):
            args = signatures.get(f'Mimir.{module}.{name}', '...')
            # Positional names/signature help, optional to preserve native defaults.
            names = [p.strip() for p in args.split(',') if p.strip()]
            params=annotations.get(f'Mimir.{module}.{name}', {})
            tsargs = ', '.join('...args: any[]' if n == '...' else
                f"{n}{'?' if params.get(n, ('any', True))[1] else ''}: {ts_type(params.get(n, ('any', True))[0])}" for n in names)
            ts += [f'    /** Native Mimir.{module}.{name}({args}). Throws on native errors. */',
                   f'    function {name}({tsargs}): MimirValue;',
                   f'    namespace {name} {{ function results(...args: any[]): MimirValue[]; }}']
            rs += [f'    /// Native Mimir.{module}.{name}({args}).',
                   f'    pub fn r#{name}(args: &[crate::Value]) -> crate::Result<crate::Value> {{ crate::call("{module}.{name}", args) }}']
        ts += ['  }']; rs += ['}']
    # model is already registered as a native alias; do not redeclare it.
    aliases = {'architectures':'Architectures','tokenizer':'Tokenizer','dataset':'Dataset','htop':'Htop','viz':'Viz'}
    ts += ['}', 'declare const arg: string[];', 'declare const CONF: Record<string, any>;',
           'declare const CONF_PATH: string;', 'declare const CONF_DIR: string;', 'declare const ROOTWORK: string;']
    for module in sorted(api): ts += [f'declare const {module}: typeof Mimir.{module};']
    for alias, module in aliases.items():
        ts += [f'declare const {alias}: typeof Mimir.{module};']
        rs += [f'pub use {module} as {alias};']
    for name in ['log','read_json','write_json']:
        ts += [f'declare const {name}: MimirFunction;']
        rs += [f'pub fn {name}(args: &[crate::Value]) -> crate::Result<crate::Value> {{ crate::call("{name}", args) }}']
    # JS compatibility alias, present in the JS bootstrap.
    ts += ['declare namespace Mimir.Architectures { const create: typeof Mimir.Model.create; }']
    rs += ['#[allow(non_snake_case)] pub mod Mimir { pub use super::*; }']
    return {lua_path: lua, ROOT/'ide/javascript/mimir.d.ts':'\n'.join(ts)+'\n',
            ROOT/'ide/rust/src/api.rs':'\n'.join(rs)+'\n',
            ROOT/'ide/api-manifest.json':json.dumps(api, indent=2, sort_keys=True)+'\n'}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary',default=str(ROOT/'bin/mimir'))
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args(); api=manifest(args.binary); stale=[]
    for path,content in generate(api).items():
        if args.check:
            if not path.exists() or path.read_text()!=content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content)
    if stale: raise SystemExit('Stale IDE helpers: '+', '.join(stale))
    print(f'IDE helpers synchronized: {len(api)} namespaces, {sum(len(v) for v in api.values())} functions')
if __name__=='__main__': main()
